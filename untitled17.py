def create_sequential_windows(data, input_width, label_width, shift):
    """
    Generates sequential input and output windows while maintaining chronological order.

    Parameters:
    - data: 1D array-like or DataFrame column.
    - input_width: Number of historical lag steps (input window size).
    - label_width: Number of future steps to forecast (output window size).
    - shift: Offset representing steps between the start of input and start of label.
             Typically shift = input_width to forecast immediately after input.
    """

    values = np.array(data, dtype=np.float32)

    total_window_size = input_width + (shift - input_width) + label_width

    X = []
    y = []

    for i in range(len(values) - total_window_size + 1):
        input_window = values[i : i + input_width]
        label_window = values[i + input_width + (shift - input_width) : i + total_window_size]
        X.append(input_window)
        y.append(label_window)

    return np.array(X), np.array(y)


INPUT_WIDTH = 24
LABEL_WIDTH = 1
SHIFT = 24

X, y = create_sequential_windows(subset_df['traffic_volume'], INPUT_WIDTH, LABEL_WIDTH, SHIFT)

print(f"Original series length: {len(subset_df)}")
print(f"Input window matrix shape (X): {X.shape} -> (samples, time_steps)")
print(f"Output window matrix shape (y): {y.shape} -> (samples, time_steps)")


print("\n--- Sample Window 1 ---")
print(f"Input (last 5 values of 24h): {X[0][-5:]}")
print(f"Target (next 1h): {y[0]}")

import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import GRU, Dense, Input


split_idx = int(len(X) * 0.8)

X_train, X_val = X[:split_idx], X[split_idx:]
y_train, y_val = y[:split_idx], y[split_idx:]


X_train = np.expand_dims(X_train, axis=-1)
X_val = np.expand_dims(X_val, axis=-1)

print(f"Train input shape: {X_train.shape}")
print(f"Validation input shape: {X_val.shape}")


model = Sequential([
    Input(shape=(INPUT_WIDTH, 1)),
    GRU(64, activation='tanh', return_sequences=False),
    Dense(32, activation='relu'),
    Dense(LABEL_WIDTH)
])

model.compile(optimizer='adam', loss='mse', metrics=['mae'])
model.summary()


history = model.fit(
    X_train, y_train,
    validation_data=(X_val, y_val),
    epochs=15,
    batch_size=32,
    verbose=1
)


plt.figure(figsize=(10, 5))
plt.plot(history.history['loss'], label='Train Loss (MSE)')
plt.plot(history.history['val_loss'], label='Validation Loss (MSE)')
plt.title('GRU Training and Validation Loss')
plt.xlabel('Epochs')
plt.ylabel('Loss (MSE)')
plt.legend()
plt.grid(True)
plt.show()

from sklearn.metrics import mean_absolute_error, mean_squared_error


predictions = model.predict(X_val)


y_true = y_val.flatten()
y_pred = predictions.flatten()


mae = mean_absolute_error(y_true, y_pred)
mse = mean_squared_error(y_true, y_pred)
rmse = np.sqrt(mse)

print("=== Model Evaluation on Validation Set ===")
print(f"Mean Absolute Error (MAE): {mae:.2f} vehicles/hour")
print(f"Root Mean Squared Error (RMSE): {rmse:.2f} vehicles/hour")



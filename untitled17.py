print("Generating a highly realistic hourly traffic volume dataset with typical smart city patterns...")
np.random.seed(42)
timestamps = pd.date_range(start="2023-01-01", periods=3000, freq="h")


hours = timestamps.hour
traffic_pattern = 1000 + 1500 * np.sin(2 * np.pi * hours / 24) + 800 * np.sin(4 * np.pi * (hours - 8) / 24) + np.random.normal(0, 300, len(timestamps))
traffic_volume = np.clip(traffic_pattern, 100, 5000).astype(int)

df = pd.DataFrame({'date_time': timestamps, 'traffic_volume': traffic_volume})
print(f"Dataset successfully created. Shape: {df.shape}")

df.set_index('date_time', inplace=True)
subset_df = df.iloc[0:2500].copy()
print(f"Selected subset shape: {subset_df.shape}")


plt.figure(figsize=(15, 5))
